"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
SHORT = ["1 week", "2 weeks", "4 weeks"]
LONG = ["12 weeks", "26 weeks"]


def headline(m: dict) -> str:
    sig, d, s, b = m["signals"], m["data"], m["sample"], m["benchmarks"]
    best = max(sig, key=lambda k: abs(sig[k]["gross"]["t"]))
    w1 = sig["1 week"]
    checks = {
        "no lookback is significant after the Holm correction": all(v["p_holm"] > 0.05 for v in sig.values()),
        "the best lookback is the 2 week sort": best == "2 weeks",
        "no reversal at one week": w1["gross"]["ann_return"] > 0,
        "no momentum at 12 or 26 weeks": all(sig[k]["gross"]["t"] < 1 for k in LONG),
        "the short leg carries the 1 to 4 week sorts": all(
            sig[k]["short_leg"]["ann_return"] > sig[k]["long_leg"]["ann_return"] and sig[k]["short_leg"]["t"] > 1.96
            and sig[k]["long_leg"]["t"] < 1.96 for k in SHORT),
        "one day of delay costs the 1 week sort a significant amount": w1["lag_cost"]["t"] > 1.96,
        "every lookback is positive in the first third and negative in the second":
            all(list(v["thirds"].values())[0]["ann_return"] > 0 > list(v["thirds"].values())[1]["ann_return"]
                for v in sig.values()),
        "the delay removes most of the 1 week return":
            w1["gross"]["ann_return"] < 0.5 * w1["same_day_gross"]["ann_return"],
        "no long-short spread changes significantly without dead coins":
            all(abs(v["minus_all"]["t"]) < 1.96 for v in m["survivors_only"].values()),
        "survivors only overstates the average coin": b["universe_survivors_minus_all"]["t"] > 1.96,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    bs = sig[best]
    return (
        f"**Answer, from {s['weeks']} weekly rebalances between {s['first_trade'][:4]} and {s['last_trade'][:4]} on "
        f"data that keeps the {d['n_stopped_trading']} coins that stopped trading: neither holds up.** None of the five "
        f"lookbacks is significant once the five tests are counted. The best, a {best[:-1]} sort, earns "
        f"{bs['gross']['ann_return']:.0%} a year before costs with t = {bs['gross']['t']:.1f}, and a corrected "
        f"p-value of {bs['p_holm']:.2f}. There is no reversal at one week and no momentum at 12 or 26 weeks. "
        f"What return there is at 1 to 4 weeks comes from the short side, losers that keep losing, which is the "
        f"side hardest to trade. Two things a careless backtest would get wrong are large here: trading at the "
        f"same close that produces the signal adds {w1['lag_cost']['ann_diff']:.0%} a year to the 1 week sort "
        f"(t = {w1['lag_cost']['t']:.1f}), and dropping coins that later died adds "
        f"{b['universe_survivors_minus_all']['ann_diff']:.0%} a year to the average coin "
        f"(t = {b['universe_survivors_minus_all']['t']:.1f})."
    )


def results(m: dict) -> str:
    sig, d, s, b, sv = m["signals"], m["data"], m["sample"], m["benchmarks"], m["survivors_only"]
    names = list(sig)
    out = [f"Data {d['first_day']} to {d['last_day']}: {d['n_assets']} assets, of which {d['n_stopped_trading']} "
           f"stopped trading before the end and {d['n_reused_symbols']} are second lives of a reused symbol. "
           f"Portfolios trade weekly from {s['first_trade']} to {s['last_trade']} ({s['weeks']} weeks). "
           f"{d['n_ever_in_universe']} assets were in the top {s['top_n']} at some point and "
           f"{d['n_ever_in_universe_stopped']} of those later stopped trading. Each side of a portfolio holds "
           f"{s['names_per_leg']} coins. Returns are arithmetic per year; t-statistics use Newey-West errors.", "",
           "### Winners minus losers", "",
           "| Lookback | Return, gross | t | p, Holm | Return, net | Sharpe, net | Max drawdown, net | Turnover per week |",
           "|---|---|---|---|---|---|---|---|"]
    for k in names:
        v = sig[k]
        out.append(f"| {k} | {v['gross']['ann_return']:+.1%} | {v['gross']['t']:+.2f} | {v['p_holm']:.2f} | "
                   f"{v['net']['ann_return']:+.1%} | {v['net']['sharpe']:+.2f} | {v['net']['max_drawdown']:.0%} | "
                   f"{v['turnover_per_week']:.0%} |")
    out += ["", f"Turnover is the sum of absolute weight changes on both sides, so 400% replaces everything. "
            f"Costs are {s['cost_bps']:.0f} bps per unit traded. For scale: the equal weighted universe returned "
            f"{b['universe']['ann_return']:+.1%} a year with {b['universe']['ann_vol']:.0%} volatility, and "
            f"Bitcoin {b['btc']['ann_return']:+.1%} with {b['btc']['ann_vol']:.0%}.", "",
            "### Which side earns it", "",
            "Return of each side against the equal weighted universe. Long is winners minus universe, short is "
            "universe minus losers; the two add up to the gross return above.", "",
            "| Lookback | Long side | t | Short side | t |", "|---|---|---|---|---|"]
    for k in names:
        v = sig[k]
        out.append(f"| {k} | {v['long_leg']['ann_return']:+.1%} | {v['long_leg']['t']:+.2f} | "
                   f"{v['short_leg']['ann_return']:+.1%} | {v['short_leg']['t']:+.2f} |")
    thirds = list(sig[names[0]]["thirds"])
    out += ["", "### Stability", "", "Gross return per year in each third of the sample.", "",
            "| Lookback | " + " | ".join(thirds) + " |", "|---|" + "---|" * len(thirds)]
    for k in names:
        out.append(f"| {k} | " + " | ".join(f"{sig[k]['thirds'][t]['ann_return']:+.0%}" for t in thirds) + " |")
    out += ["", "### What one day of delay is worth", "",
            f"The same portfolios traded at the close that produces the signal, against the reported ones that "
            f"wait {s['lag_days']} day.", "",
            "| Lookback | Same close | t | One day later | t | Difference | t |", "|---|---|---|---|---|---|---|"]
    for k in names:
        v = sig[k]
        out.append(f"| {k} | {v['same_day_gross']['ann_return']:+.1%} | {v['same_day_gross']['t']:+.2f} | "
                   f"{v['gross']['ann_return']:+.1%} | {v['gross']['t']:+.2f} | {v['lag_cost']['ann_diff']:+.1%} | "
                   f"{v['lag_cost']['t']:+.2f} |")
    out += ["", "### What delisted coins are worth", "",
            "The same study with the universe limited to coins still trading in the final month.", "",
            "| Portfolio | All coins | Survivors only | Difference | t |", "|---|---|---|---|---|",
            f"| Equal weighted universe | {b['universe']['ann_return']:+.1%} | "
            f"{b['universe_survivors_only']['ann_return']:+.1%} | {b['universe_survivors_minus_all']['ann_diff']:+.1%} | "
            f"{b['universe_survivors_minus_all']['t']:+.2f} |"]
    for k in names:
        out.append(f"| {k} winners minus losers | {sig[k]['gross']['ann_return']:+.1%} | "
                   f"{sv[k]['gross']['ann_return']:+.1%} | {sv[k]['minus_all']['ann_diff']:+.1%} | "
                   f"{sv[k]['minus_all']['t']:+.2f} |")
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
